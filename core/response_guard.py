"""
Response Guard for AI-Powered Campus Helpdesk Assistant.
Validates model-generated answers against retrieved context sources.
Flags and strips any hallucinated citations (documents or pages not present
in the retrieved chunk set) and appends a verified disclosure notice.
"""

import re
from typing import List, Tuple, Set, Dict, Any, Optional

from core.logger import logger
from core.exceptions import UnverifiedCitationError


# Citation regex patterns matching various LLM citation formats:
# [Source: handbook.pdf, Page: 3], [Source: handbook.pdf | Page: 3],
# [handbook.pdf, Page 3], (handbook.pdf, Page 3), [Source: handbook.pdf, p. 3]
CITATION_PATTERNS = [
    re.compile(
        r'\[\s*(?:Source:\s*)?([a-zA-Z0-9_\-\.\s]+\.pdf)[\s,\|]+(?:Page|page|p\.)\s*[:\s]*(\d+)\s*\]',
        re.IGNORECASE
    ),
    re.compile(
        r'\(\s*(?:Source:\s*)?([a-zA-Z0-9_\-\.\s]+\.pdf)[\s,\|]+(?:Page|page|p\.)\s*[:\s]*(\d+)\s*\)',
        re.IGNORECASE
    ),
    re.compile(
        r'(?:Source:\s*)([a-zA-Z0-9_\-\.\s]+\.pdf)[\s,\|]+(?:Page|page|p\.)\s*[:\s]*(\d+)',
        re.IGNORECASE
    ),
]


def extract_citations_from_text(text: str) -> List[Tuple[str, str, int]]:
    """
    Finds all citation mentions in text in original character order.
    Returns list of tuples: (full_matched_string, filename, page_number).
    """
    found = []
    seen_spans = set()

    for pattern in CITATION_PATTERNS:
        for match in pattern.finditer(text):
            span = match.span()
            if any(s[0] <= span[0] and span[1] <= s[1] for s in seen_spans):
                continue
            seen_spans.add(span)
            raw_match = match.group(0)
            raw_filename = match.group(1).strip()
            raw_page = int(match.group(2).strip())
            found.append((span[0], raw_match, raw_filename, raw_page))

    # Sort in natural reading order by start offset
    found.sort(key=lambda x: x[0])
    return [(m[1], m[2], m[3]) for m in found]


def validate_and_guard_response(
    answer: str,
    valid_sources: List[Any]
) -> Tuple[str, List[Dict[str, Any]]]:
    """
    Inspects answer for citations and validates against valid_sources.
    
    Args:
        answer: The text generated by the model.
        valid_sources: List of SourceCitation, RetrievedChunk, TextChunk, or dicts.
        
    Returns:
        Tuple of (guarded_answer, list_of_removed_citations).
        If unverified citations are found, they are stripped/replaced in the answer,
        and an unverified citation notice is appended.
    """
    if not answer or not valid_sources:
        return answer, []

    # Build set of verified (filename, page) pairs
    valid_pairs: Set[Tuple[str, int]] = set()
    for s in valid_sources:
        if hasattr(s, "filename") and hasattr(s, "page"):
            valid_pairs.add((s.filename.strip().lower(), int(s.page)))
        elif hasattr(s, "chunk"):
            valid_pairs.add((s.chunk.filename.strip().lower(), int(s.chunk.page)))
        elif isinstance(s, dict):
            fname = s.get("filename", "")
            page = s.get("page", 1)
            valid_pairs.add((fname.strip().lower(), int(page)))

    extracted = extract_citations_from_text(answer)
    if not extracted:
        return answer, []

    removed_citations = []
    cleaned_answer = answer

    for raw_match, raw_fn, raw_pg in extracted:
        normalized_fn = raw_fn.strip().lower()
        if (normalized_fn, raw_pg) not in valid_pairs:
            # Hallucinated / unverified citation detected!
            logger.warning(
                f"ResponseGuard flagged unverified citation: '{raw_fn}' Page {raw_pg} "
                f"(not present in verified retrieved sources {valid_pairs})"
            )
            removed_citations.append({
                "match": raw_match,
                "filename": raw_fn,
                "page": raw_pg
            })
            # Strip or mark the citation in text
            cleaned_answer = cleaned_answer.replace(raw_match, "[Unverified citation removed]")

    if removed_citations:
        notes = []
        for c in removed_citations:
            notes.append(f"• `{c['filename']}` (Page {c['page']})")
        
        notice = (
            "\n\n> ⚠️ **Notice: Unverified citation(s) removed.**\n"
            "> The following citations were not present in the retrieved official document context and were removed:\n"
            + "\n".join(f"> {n}" for n in notes)
        )
        cleaned_answer = cleaned_answer.strip() + notice

    return cleaned_answer, removed_citations
